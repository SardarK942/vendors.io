/**
 * Custom-request flow — UI-driven E2E.
 *
 * v1 of this spec posted straight to `/api/bookings/custom-request` and never
 * touched the form. v2 (the modal + 3-step flow: Step1Shape → Step2Details →
 * Step3Review) is the whole point of this rewrite: drive the real DOM.
 *
 * Five scenarios:
 *   A) Single event, full happy path through the modal, ending on "Request sent".
 *   B) Multi-day (3 events) — fills all three per-day cards via data-testid
 *      scoping and reaches Step 3.
 *   C) Ordering guard — re-picking an earlier event's date to *after* a later
 *      event's date clears the later one (Step2Details' ascending-date
 *      invariant).
 *   D) Guest-count field allows clearing the seeded "50" and retyping freely
 *      (regression guard for the old leading-"1" lock bug).
 *   E) Deep-link fallback — `/vendors/[slug]/request` still renders the flow
 *      inline with a "Back to {business_name}" link.
 *
 * Calendar interaction notes:
 * - The DatePicker wraps react-day-picker v10. Each day button's accessible
 *   name is generated by `labelDayButton` as date-fns' locale "PPPP" format
 *   ("EEEE, MMMM do, y", e.g. "Friday, October 3rd, 2025"), with "Today, "
 *   prefixed / ", selected" suffixed when applicable. We reproduce that
 *   formatting locally (see `formatDayLabel`) rather than depending on
 *   `date-fns` directly, since it's only a transitive dependency here.
 * - The "next month" nav button's accessible name is the library's default
 *   "Go to the Next Month" (see react-day-picker's `labelNext`).
 * - To keep dates unambiguous regardless of what day it is when the suite
 *   runs, every scenario navigates one calendar month forward and picks a
 *   day-of-month via `pickCalendarDate`, scoped to the `data-testid` added to
 *   Step2Details in this same PR (`event-card-${idx}` / `date-picker-${idx}`).
 */

import { test, expect, type Locator, type Page } from '@playwright/test';
import { seedCouple, seedVendor, cleanup, type TestUser, type TestVendor } from './helpers/seed';
import { loginAs } from './helpers/login';

// ---------------------------------------------------------------------------
// Date helpers — mirror react-day-picker's default "PPPP" day-button label.
// ---------------------------------------------------------------------------

function ordinal(n: number): string {
  const j = n % 10;
  const k = n % 100;
  if (j === 1 && k !== 11) return `${n}st`;
  if (j === 2 && k !== 12) return `${n}nd`;
  if (j === 3 && k !== 13) return `${n}rd`;
  return `${n}th`;
}

/** Reproduces date-fns' en-US "PPPP" format: "EEEE, MMMM do, y". */
function formatDayLabel(date: Date): string {
  const weekday = date.toLocaleDateString('en-US', { weekday: 'long' });
  const month = date.toLocaleDateString('en-US', { month: 'long' });
  const year = date.getFullYear();
  return `${weekday}, ${month} ${ordinal(date.getDate())}, ${year}`;
}

/**
 * A future date `monthsAhead` calendar months from today, on `dayOfMonth`.
 * Clamps via setDate(1) first so month-end overflow (e.g. Jan 31 + 1 month)
 * never rolls into an unexpected month.
 */
function futureDate(monthsAhead: number, dayOfMonth: number): Date {
  const d = new Date();
  d.setDate(1);
  d.setMonth(d.getMonth() + monthsAhead);
  d.setDate(dayOfMonth);
  return d;
}

/** Clicks the DatePicker's "next month" nav `monthsAhead` times, then the target day. */
async function pickCalendarDate(scope: Locator, monthsAhead: number, dayOfMonth: number) {
  for (let i = 0; i < monthsAhead; i++) {
    await scope.getByRole('button', { name: /go to the next month/i }).click();
  }
  const date = futureDate(monthsAhead, dayOfMonth);
  await scope.getByRole('button', { name: formatDayLabel(date) }).click();
  return date;
}

